/**
 * 「刷新当前页」的**登记处** —— 外壳 navbar 上那个刷新图标靠它工作。
 *
 * # ⚠⚠ 它为什么**不是**信号（这条是踩出来的，别改回去）
 *
 * 第一版用的是 lite 信号（`ref`）+ 页面在挂载时写它。后果离病因很远，但很严重：
 * **切页时旧页面不再被替换，新页面被追加** ✗ —— `#app` 里的卡片数 64 → 108 → 153 → …
 * 一路累加，页面上同时挂着好几个页面，某一页的转圈永远留在 DOM 里；真 DOM 验收
 * 从「6 条全绿」变成「28 条失败」✗。
 *
 * 机理：lite 是**同步刷新**的（`web/lite/compiler.ts` 里事件处理器要自动包 `batch`，
 * 注释写着"本实现是同步刷新，不包的话连续写多个信号会刷多遍"）。而页面**挂载的时刻**，
 * 正是外壳在渲染这一页的过程中 ⇒ 此刻写信号会**重入外壳的渲染** ⇒ 页面槽位的替换
 * 逻辑被打断：新页面被追加、旧页面留在原地 ✗。
 *
 * 实测两条（2026-10-03，各一次构建就能分辨）：
 * * 把**读取**隔离进独立组件（`RefreshButton`）⇒ **没用** ✗ —— 病因是**写**，不是读；
 * * 把 `setPageRefresh` 改成空操作 ⇒ 立刻恢复正常 ✓ ⇒ 就是这次写入的锅。
 *
 * 所以这里用**普通模块变量**：挂载期间零信号写入 ✓；navbar 那个按钮点击时读**当前值**
 * （`refreshNow()`）⇒ 动作永远是对的 ✓。
 * 代价：按钮的「转圈 / 置灰」这种**外观**没法跟着页面加载态实时变（那需要响应式 ✗）——
 * 所以不做：点了就点，页面自己的 `load()` 是幂等的 ✓。
 *
 * ⚠ 将来若非得让它响应式，**别在页面挂载路径上写信号**：要么改 lite 的刷新时机，
 * 要么把写入推迟到挂载之后（例如页面首次 `load()` 的 `finally` 里），
 * 并且先量一遍"切页不追加"再合。
 *
 * # 为什么不是"外壳重新挂载当前页"
 *
 * 用户口径（2026-10-03）：「刷新做成图标放上面可行吗」。把按钮搬到 navbar 很容易，
 * 难的是**搬的是什么动作**：
 *
 * * 让外壳把当前页**重新挂载**一遍 ⇒ `onMounted` 会再跑一次 `load()` ✓，
 *   但页面状态**全丢** ✗ —— 任务页正在看的日志、勾好的账号、滚动位置、
 *   编排页填了一半的表单，全没了。那比"刷新按钮留在下面"糟得多。
 * * 所以让**页面把自己的 `load()` 登记给外壳** ✓：图标点的还是那个页面的
 *   `load()`，与页头原来的按钮**一模一样**，什么都不丢 ✓。
 *
 * # 为什么不用 props 传
 *
 * 页面是外壳动态 `import` 出来再建的（见 `app.tsx`），没有任何一层"父组件传参"可以借道；
 * 而这一层的状态**只有一份**（当前页是谁就登记谁），所以一个模块级变量就是它的正确形状 ✓
 * —— 与 `ui/auth-signal.ts` 同一个套路。
 *
 * # 契约：登记返回"上一份"，卸载时**还回去**
 *
 * 页面挂载时 `const prev = setPageRefresh({ run })`、卸载时 `setPageRefresh(prev)`。
 * ⚠ 为什么要"还回去"而不是直接置 `null`：**子视图会盖住外层** ——
 * 任务页里的配置视图（`config-page.tsx`）也要刷新，它挂载时登记自己那份 ✓，
 * 但卸载时若写 `null`，任务页那份就被清掉了 ✗ ⇒ 回到列表后 navbar 的刷新图标
 * 点了没反应（而页面明明还能刷新）。返回上一份就自然解决：谁盖的谁还 ✓。
 * 栈不需要：本仓最多两层（页面 → 子视图）。
 */

export interface PageRefresh {
  /** 真正干活的那个：就是页面自己的 `load()`。 */
  run: () => void
}

/**
 * 当前页登记的刷新动作。`null` = 这一页没有可刷新的东西。
 *
 * ⚠ **普通变量、不是信号** —— 理由见文件头那段。
 */
let current: PageRefresh | null = null

/**
 * 登记（或撤销）当前页的刷新动作，**返回被覆盖的那一份**。
 *
 * 用法：`const prev = setPageRefresh({ run: () => void load() })` … 卸载时 `setPageRefresh(prev)`。
 * 最外层页面 `prev` 就是 `null`，等价于原来的写法 ✓。
 */
export const setPageRefresh = (refresh: PageRefresh | null): PageRefresh | null => {
  const prev = current
  current = refresh
  return prev
}

/** 外壳那个图标点下去时调它：读**当前**登记的那一份；没登记就什么都不做。 */
export const refreshNow = (): void => {
  current?.run()
}
